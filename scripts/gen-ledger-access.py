#!/usr/bin/env python3
"""Write src/session/ledger-access.ts from the Formulon name ledger.

The ledger (`tools/api/names.yaml` in the formulon repository) names every
binding operation `<noun>.<verb>` with its JavaScript spelling. This script
records whether the ledger's verb only reads (`get`, `list`, `evaluate`, `has`,
a handle accessor, ...) or may change the workbook, both per JavaScript method
name and per handle method (`PivotCache.refresh`), whose name the formulon
repository's API conventions derive from the entry's `handle:`. A name spelled
with conflicting verbs is recorded as a write, so a session is never left
wrongly clean.

Usage: python3 scripts/gen-ledger-access.py <path to formulon>/tools/api/names.yaml
(needs PyYAML).
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parents[1] / "src" / "session" / "ledger-access.ts"

# Verbs that only read. A verb outside this set (set, add, recalc, convert, apply, ...) is a write.
READ_PREFIXES = (
    "get",
    "list",
    "evaluate",
    "resolve",
    "format",
    "parse",
    "find",
    "validate",
    "is",
    "has",
    "compare",
    "localize",
    "canonicalize",
    "iter",
    "disposed",
)
# Verbs that hand out a handle or a namespace object without changing anything.
ACCESSOR_VERBS = {
    "sheet",
    "sheet_table",
    "table",
    "pivot",
    "pivot_cache",
    "drawing",
    "picture",
    "chart",
    "shape",
    "slicer",
    "ooxml",
    "sheet_iterator",
    "raw_sheet_count",
}


def access_of(verb: str) -> str:
    if verb in ACCESSOR_VERBS or verb.startswith(READ_PREFIXES):
        return "read"
    return "write"


def quote(name: str) -> str:
    return f'"{name}"' if "." in name else name


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[-2], file=sys.stderr)
        return 2
    ledger_path = Path(argv[1]).resolve()
    sys.path.insert(0, str(ledger_path.parents[1] / "dev"))
    from binding_drift.api_conventions import handle_classes, handle_name

    ledger = yaml.safe_load(ledger_path.read_text(encoding="utf-8"))
    entries = ledger["entries"]
    collections = ledger.get("collections", {})
    access: dict[str, str] = {}

    def record(name: str, kind: str) -> None:
        access[name] = "write" if access.get(name, kind) != kind else kind

    for key, entry in entries.items():
        if not isinstance(entry, dict) or entry.get("kind") != "op" or "drop" in entry:
            continue
        name = entry.get("js")
        if not name:
            continue
        kind = access_of(key.rsplit(".", 1)[-1])
        record(name, kind)
        method = handle_name(entry, "js", collections)
        if method:
            for cls in handle_classes(entry):
                record(f"{cls}.{method}", kind)
    lines = [
        "// Generated by scripts/gen-ledger-access.py from the Formulon name ledger; do not edit.",
        "",
        "/** Whether each JavaScript method the ledger names (bare, or `Class.method` on a handle) only reads or may change the workbook. */",
        'export const LEDGER_ACCESS: Readonly<Record<string, "read" | "write">> = {',
    ]
    lines += [f'  {quote(name)}: "{access[name]}",' for name in sorted(access)]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[2])}: {len(access)} methods")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
