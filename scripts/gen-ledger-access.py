#!/usr/bin/env python3
"""Write src/session/ledger-access.ts from the Formulon name ledger.

The ledger (`tools/api/names.yaml` in the formulon repository) names every
binding operation `<noun>.<verb>` with its JavaScript spelling. This script
records, per JavaScript method name, whether the ledger's verb only reads
(`get`, `list`, `evaluate`, `has`, a handle accessor, ...) or may change the
workbook. A name the ledger spells with conflicting verbs is recorded as a
write, so a session is never left wrongly clean.

Usage: python3 scripts/gen-ledger-access.py <path to formulon>/tools/api/names.yaml
(needs PyYAML).
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parents[1] / "src" / "session" / "ledger-access.ts"

# Verbs that only read. A verb outside this set (set, add, recalc, convert, apply, ...) is a write.
READ_PREFIXES = (
    "get",
    "list",
    "evaluate",
    "resolve",
    "format",
    "parse",
    "find",
    "validate",
    "is",
    "has",
    "compare",
    "localize",
    "canonicalize",
    "iter",
    "disposed",
)
# Verbs that hand out a handle or a namespace object without changing anything.
ACCESSOR_VERBS = {
    "sheet",
    "sheet_table",
    "table",
    "pivot",
    "pivot_cache",
    "drawing",
    "picture",
    "chart",
    "shape",
    "slicer",
    "ooxml",
    "sheet_iterator",
    "raw_sheet_count",
}


def access_of(verb: str) -> str:
    if verb in ACCESSOR_VERBS or verb.startswith(READ_PREFIXES):
        return "read"
    return "write"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[-2], file=sys.stderr)
        return 2
    entries = yaml.safe_load(Path(argv[1]).read_text(encoding="utf-8"))["entries"]
    access: dict[str, str] = {}
    for key, entry in entries.items():
        if not isinstance(entry, dict) or entry.get("kind") != "op" or "drop" in entry:
            continue
        name = entry.get("js")
        if not name:
            continue
        verb = key.rsplit(".", 1)[-1]
        kind = access_of(verb)
        access[name] = "write" if access.get(name, kind) != kind else kind
    lines = [
        "// Generated by scripts/gen-ledger-access.py from the Formulon name ledger; do not edit.",
        "",
        "/** Whether each JavaScript method the ledger names only reads (`read`) or may change the workbook. */",
        'export const LEDGER_ACCESS: Readonly<Record<string, "read" | "write">> = {',
    ]
    lines += [f'  {name}: "{access[name]}",' for name in sorted(access)]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[2])}: {len(access)} methods")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
